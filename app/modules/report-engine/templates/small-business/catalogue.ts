export type FilingMode = 'monthly' | 'annual';
export const columnLabels = (mode: FilingMode) =>
  mode === 'monthly' ? ['本年累计金额', '本月金额'] : ['本年累计金额', '上年金额'];

/** 资产负债表左右并列表，保持制度行次。 */
export function balanceAddress(line: number, column: 'closing' | 'yearOpening') {
  if (!Number.isInteger(line) || line < 1 || line > 53) throw new Error('资产负债表行次无效');
  return `${line <= 30 ? (column === 'closing' ? 'C' : 'D') : column === 'closing' ? 'G' : 'H'}${line <= 30 ? line + 5 : line - 25}`;
}

export function statementAddress(line: number, column: 'ytd' | 'comparison') {
  return `${column === 'ytd' ? 'C' : 'D'}${line + 5}`;
}
