/** 财会〔2019〕6号附件2；页码为 PDF 页码。这里只定义报表项目，不定义会计科目表。 */
export type Line = {
  key: string;
  label: string;
  page: number;
  section?: boolean;
  /** 仅在所有直接组成项均已取数时启用合计，不跳过待配置项。 */
  total?: { key: string; sign: 1 | -1 }[];
};
const line = (key: string, label: string, page: number): Line => ({ key, label, page });
const section = (key: string, label: string, page: number): Line => ({
  ...line(key, label, page),
  section: true,
});
const total = (
  key: string,
  label: string,
  page: number,
  plus: string[],
  minus: string[] = [],
): Line => ({
  ...line(key, label, page),
  total: [
    ...plus.map((key) => ({ key, sign: 1 as const })),
    ...minus.map((key) => ({ key, sign: -1 as const })),
  ],
});

